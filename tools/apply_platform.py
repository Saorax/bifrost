"""add the extension layer to the AS3 tree: platform sources and hook call sites.

    python tools/apply_platform.py [--version 10.11] [--mod hooktest]

two things go into ``src/as3/<ver>/scripts`` (the tree ``data/tools/compile_as3.py`` compiles):

1. the AS3 sources under ``src/platform/as3/`` (package ``bh.platform``, the hook layer) plus the mods named with
   ``--mod`` (``bh/mods/<mod>/``), and a generated ``bh/platform/ModList.as`` that registers those mods;
2. the hook call sites from ``src/platform/patches.json``: each patch names a file, a function (``s/method/name``,
   ``i/getter/name``, ... as ``tools/as3_edits.py`` keys them), where to insert (``before``/``after`` an anchor
   that must match exactly one line, or the ``start``/``end`` of the body) and the imports it needs. Inserted lines
   end with ``// bh-platform:<id>``; a patch whose marker is already in the file is skipped, and marked lines of a
   patch no longer wanted are removed, so the method goes back to its original bytecode.

every patch is a direct edit to original code, listed in ``MODIFICATIONS.md``; ``tools/splice_as3.py`` compiles the
patched methods from AS3 and keeps everything else's original bytecode.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools import as3_edits

PLATFORM = ROOT / "src" / "platform"


class PatchError(Exception):
    pass


def function_span(lines: list[str], key: str) -> tuple[int, int, int]:
    static, kind, name = key.split("/")
    accessor = {"getter": r"get\s+", "setter": r"set\s+"}.get(kind, "")
    header = re.compile(rf"^\s*((?:\w+\s+)*)function\s+{accessor}{re.escape(name)}\s*\(")
    hits = []
    for i, line in enumerate(lines):
        m = header.match(line)
        if m and (("static" in m.group(1).split()) == (static == "s")):
            hits.append(i)
    if len(hits) != 1:
        raise PatchError(f"function {key}: {len(hits)} matches")
    start = hits[0]
    text = "\n".join(lines)
    offset = sum(len(l) + 1 for l in lines[:start])
    open_at = text.find("{", offset)
    close_at = as3_edits._match_brace(text, open_at) - 1
    return start, text.count("\n", 0, open_at), text.count("\n", 0, close_at)


def apply_patch(lines: list[str], patch: dict) -> tuple[list[str], bool]:
    marker = f"// bh-platform:{patch['id']}"
    if any(marker in line for line in lines):
        return lines, False
    _, open_line, close_line = function_span(lines, patch["function"])
    where = patch["where"]
    if where in ("before", "after"):
        hits = [i for i in range(open_line + 1, close_line) if lines[i].strip() == patch["anchor"]]
        if len(hits) != 1:
            raise PatchError(f"{patch['id']}: anchor {patch['anchor']!r} matches {len(hits)} lines of {patch['function']}")
        at = hits[0] + (1 if where == "after" else 0)
        indent = re.match(r"\s*", lines[hits[0]]).group(0)
    elif where in ("start", "end"):
        brace = lines[open_line]
        indent = re.match(r"\s*", brace).group(0) + "   "
        at = open_line + 1 if where == "start" else close_line
    else:
        raise PatchError(f"{patch['id']}: unknown where {where!r}")
    new = lines[:at] + [f"{indent}{code} {marker}" for code in patch["insert"]] + lines[at:]
    for imp in patch.get("imports", []):
        if not any(l.strip() == f"import {imp};" for l in new):
            pkg = next(i for i, l in enumerate(new) if l.strip().startswith("package"))
            brace = next(i for i in range(pkg, len(new)) if "{" in new[i])
            new.insert(brace + 1, f"   import {imp};")
    return new, True


def mod_list(mods: list[str]) -> str:
    imports = "".join(f"   import bh.mods.{m}.{mod_class(m)};\n" for m in mods)
    calls = "".join(f"         {mod_class(m)}.register();\n" for m in mods)
    return ("package bh.platform\n{\n" + imports +
            "\n   /** Generated by tools/apply_platform.py: the mods built into this SWF. */\n"
            "   public final class ModList\n   {\n      public function ModList()\n      {\n      }\n\n"
            "      public static function registerAll() : void\n      {\n" + calls + "      }\n   }\n}\n")


def mod_folder(mod: str) -> Path:
    shipped = PLATFORM / "as3" / "bh" / "mods" / mod
    private = PLATFORM.parents[1] / "data" / "mods" / mod
    return private if not shipped.exists() and private.exists() else shipped


def mod_class(mod: str) -> str:
    folder = mod_folder(mod)
    classes = sorted(p.stem for p in folder.glob("*Mod.as"))
    if len(classes) != 1:
        raise PatchError(f"mod {mod}: expected one *Mod.as in {folder}, found {classes}")
    return classes[0]


MARKER = re.compile(r"// bh-platform:([A-Za-z0-9_.-]+)\s*$")


def remove_stale(tree: Path, wanted: set[str]) -> list[str]:
    removed = set()
    for path in tree.rglob("*.as"):
        if path.parts[len(tree.parts):len(tree.parts) + 1] == ("bh",):
            continue
        text = path.read_text(encoding="utf-8")
        if "// bh-platform:" not in text:
            continue
        lines = text.splitlines()
        kept = []
        for line in lines:
            m = MARKER.search(line)
            if m and m.group(1) not in wanted:
                removed.add(m.group(1))
                continue
            kept.append(line)
        if len(kept) != len(lines):
            path.write_text(chr(10).join(kept), encoding="utf-8")
    return sorted(removed)


def apply(tree: Path, mods: list[str]) -> dict:
    report = {"copied": [], "patched": [], "already": []}
    src = PLATFORM / "as3"
    for path in sorted(src.rglob("*.as")):
        rel = path.relative_to(src)
        if rel.parts[:2] == ("bh", "mods") and rel.parts[2] not in mods:
            continue
        dest = tree / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, dest)
        report["copied"].append(rel.as_posix())
    for mod in mods:
        folder = mod_folder(mod)
        if folder.parent == src / "bh" / "mods":
            continue
        for path in sorted(folder.rglob("*.as")):
            rel = Path("bh") / "mods" / mod / path.relative_to(folder)
            dest = tree / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, dest)
            report["copied"].append(rel.as_posix())
    mod_dir = tree / "bh" / "mods"
    if mod_dir.exists():
        for folder in mod_dir.iterdir():
            if folder.is_dir() and folder.name not in mods:
                shutil.rmtree(folder)
    (tree / "bh" / "platform" / "ModList.as").write_text(mod_list(mods), encoding="utf-8")
    patches = json.loads((PLATFORM / "patches.json").read_text(encoding="utf-8"))["patches"]
    wanted = {p["id"] for p in patches if p.get("mode") != "bytecode"}
    report["removed"] = remove_stale(tree, wanted)
    for patch in patches:
        if patch.get("mode") == "bytecode":
            report["bytecode"] = report.get("bytecode", 0) + 1
            continue
        path = tree / patch["file"]
        lines = path.read_text(encoding="utf-8").split("\n")
        lines, done = apply_patch(lines, patch)
        if done:
            path.write_text("\n".join(lines), encoding="utf-8")
        report["patched" if done else "already"].append(patch["id"])
    return report


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--version", default="10.11")
    p.add_argument("--tree", type=Path)
    p.add_argument("--mod", action="append", default=[], help="platform mod to build in (bh/mods/<mod>)")
    p.add_argument("--platform", type=Path, help="the extension layer to apply (default src/platform; "
                                                 "tools/port_platform.py writes one for another version)")
    args = p.parse_args(argv)
    global PLATFORM
    PLATFORM = args.platform or PLATFORM
    tree = args.tree or ROOT / "src" / "as3" / args.version / "scripts"
    try:
        report = apply(tree, args.mod)
    except PatchError as e:
        print(f"apply_platform FAILED: {e}", file=sys.stderr)
        return 1
    print(f"platform: {len(report['copied'])} files, {len(report['patched'])} patches applied, "
          f"{len(report['already'])} already present, {report.get('bytecode', 0)} left for bytecode, mods: {', '.join(args.mod) or 'none'}"
          + (f", removed stale patches: {', '.join(report['removed'])}" if report.get("removed") else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
