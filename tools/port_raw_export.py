"""exports the raw game's native port: the raw game in one folder, the engine that builds and runs it in another.

    python tools/port_raw_export.py --out C:/Coding/BRAWLHALLA PROJECTS/bh-raw/bh-game [--engine C:/Coding/BRAWLHALLA PROJECTS/bh-new-engine] [--convert]
                                    [--openfl-engine C:/Coding/bh-port-engine-openfl] [--openfl-only] [--no-build]

the raw game (``--out``): ``src/``, the game converted to Haxe exactly as the converter writes it (no hooks, no
mods), and ``README.md``.

the engine (``--engine``, default ``bh-port-engine`` beside the raw game's folder), the Heaps engine: ``src/`` (the
``flash.*`` stand-ins), ``runtime/``, ``lib/`` (Heaps and its libraries, ``lib/heaps-patched``), ``tools/haxe``,
``bin/`` (HashLink; after ``build.bat`` ``game-dx11.hl``, ``game-dx12.hl`` and ``launcher.hl``), ``bin-vulkan/`` (the
same runtime with DXVK), ``build-dx11.hxml``, ``build-dx12.hxml``, ``launcher.hxml``, ``build.bat``, ``run.bat`` (the
launcher: ``storage/engine.json``'s renderer picks the game) and ``README.md``.

``--openfl-engine`` (default ``bh-port-engine-openfl`` beside the raw game's folder) holds the OpenFL engine the Heaps
build is generated from; ``--openfl-only`` writes only the raw game and that folder.

both folders hold decompiled game code: local use only, never commit or share them. they are regenerated on each
export (make lasting changes in the converter or ``port/runtime``). without ``--no-build`` the exporter builds with
the engine's own ``build.bat`` to prove the two folders compile alone.
"""
