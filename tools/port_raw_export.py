def _claim(folder: Path, marker: str) -> bool:
    folder.mkdir(parents=True, exist_ok=True)
    if any(folder.iterdir()) and not (folder / marker).exists():
        print(f"{folder} is not empty and is not an earlier export (no {marker}); refusing to write there")
        return False
    return True


def export(out: Path, *, convert: bool, game: Path, engine: Path | None = None, game_only: bool = False) -> int:
    engine = engine or out.parent / ENGINE_NAME
    if out == engine or out.is_relative_to(engine) or engine.is_relative_to(out):
        print(f"the raw game ({out}) and the engine ({engine}) need folders of their own")
        return 1
    if not _claim(out, MARKER) or not _claim(engine, ENGINE_MARKER):
        return 1
    if port_haxe_compile.BIFROST:
        print("port_raw_export: the Bifrost tree is active in this process; refusing to export it as the raw game")
        return 1
    started = time.monotonic()
    rc = port_haxe_compile.hl_check(convert=convert, export=(out, engine))
    if rc != 0:
        return rc
    for name in OLD_LAYOUT:
        old = out / name
        if old.is_dir():
            shutil.rmtree(old)
        elif old.exists():
            old.unlink()
    if game_only:
        (out / MARKER).write_text("Generated by tools/port_raw_export.py; safe to replace with a new export.\n",
                                  encoding="utf-8")
        print(f"exported the raw game in {time.monotonic() - started:.0f} s: {out}")
        return 0
    for name, source in (("openfl", port_haxe_compile.OPENFL_SRC.parent), ("lime", port_haxe_compile.LIME_SRC.parent)):
        target = engine / "lib" / name
        shutil.rmtree(target, ignore_errors=True)
        shutil.copytree(source / "src", target / "src")
        for extra in ("LICENSE.md", "NOTICE.md", "haxelib.json", "extraParams.hxml", "include.xml"):
            if (source / extra).exists():
                shutil.copy2(source / extra, target / extra)
    haxe_dir = port_haxe_compile.HAXE.parent
    if not (engine / "tools" / "haxe" / "haxe.exe").exists():
        shutil.copytree(haxe_dir, engine / "tools" / "haxe", dirs_exist_ok=True)
    port_hl_run.prepare(engine / "bin")
    files = sum(1 for _ in (out / "src").rglob("*.hx"))
    aliases = sum(1 for path in (engine / "runtime" / "flash").rglob("*.hx")
                  if "typedef" in path.read_text(encoding="utf-8") and "= openfl." in path.read_text(encoding="utf-8"))
    game_src = (out / "src").as_posix()
    include = port_haxe_compile.HL_FULL_INCLUDE_MACRO.replace("['src']", f"['{game_src}', 'runtime']")
    if include == port_haxe_compile.HL_FULL_INCLUDE_MACRO:
        raise ValueError("HL_FULL_INCLUDE_MACRO no longer names the 'src' class path")
    (engine / "build.hxml").write_text(HXML.format(game=game_src, include=include, main=port_haxe_compile.HL_MAIN),
                                       encoding="utf-8")
    (engine / "build.bat").write_text(BUILD_BAT.format(game=out), encoding="utf-8", newline="\r\n")
    (engine / "run.bat").write_text(RUN_BAT.format(game=game), encoding="utf-8", newline="\r\n")
    when = time.strftime("%Y-%m-%d %H:%M")
    (out / "README.md").write_text(README.format(when=when, root=ROOT, files=files, engine=engine, out=out),
                                   encoding="utf-8")
    (engine / "README.md").write_text(ENGINE_README.format(when=when, root=ROOT, game=out, install=game,
                                                           aliases=aliases), encoding="utf-8")
    (out / MARKER).write_text("Generated by tools/port_raw_export.py; safe to replace with a new export.\n",
                              encoding="utf-8")
    (engine / ENGINE_MARKER).write_text("Generated by tools/port_raw_export.py; safe to replace with a new export.\n",
                                        encoding="utf-8")
    print(f"exported in {time.monotonic() - started:.0f} s: the raw game in {out}, the engine in {engine}")
    return 0


def export_heaps(out: Path, engine: Path, openfl: Path, game: Path) -> int:
    from tools import port_heaps_stubs
    if port_heaps_stubs.ENGINE.resolve() != openfl or port_heaps_stubs.GAME.resolve() != (out / "src"):
        print(f"the Heaps build reads {port_heaps_stubs.ENGINE} and {port_heaps_stubs.GAME}"
              f" (tools/port_heaps_stubs.py): export the Heaps engine from those folders")
        return 1
    if not _claim(engine, HEAPS_MARKER):
        return 1
    (engine / HEAPS_MARKER).write_text("Generated by tools/port_raw_export.py; safe to replace with a new export.\n",
                                       encoding="utf-8")
    started = time.monotonic()
    rc = copy_heaps_engine(engine)
    if rc != 0:
        return rc
    write_heaps_hxml(engine, (out / "src").as_posix(), "The raw game")
    (engine / "build.bat").write_text(HEAPS_BUILD_BAT.format(game=out), encoding="utf-8", newline="\r\n")
    (engine / "run.bat").write_text(HEAPS_RUN_BAT.format(game=game), encoding="utf-8", newline="\r\n")
    (engine / "run-input-test.bat").write_text(HEAPS_INPUT_TEST_BAT, encoding="utf-8", newline="\r\n")
    (engine / "README.md").write_text(HEAPS_README.format(when=time.strftime("%Y-%m-%d %H:%M"), root=ROOT, game=out,
                                                          openfl=openfl), encoding="utf-8")
    (engine / HEAPS_MARKER).write_text("Generated by tools/port_raw_export.py; safe to replace with a new export.\n",
                                       encoding="utf-8")
    print(f"exported the Heaps engine in {time.monotonic() - started:.0f} s: {engine}")
    return 0


HEAPS_LIBRARIES = {"heaps": "lib/heaps", "format": "lib/format", "hldx": "lib/hldx", "hlsdl": "lib/hlsdl",
                   "hlopenal": "lib/hlopenal"}


def copy_heaps_engine(engine: Path) -> int:
    from tools import port_heaps, port_heaps_stubs
    rc = port_heaps_stubs.stubs(True)
    if rc != 0:
        return rc
    for name, source in (("src", port_heaps_stubs.OUT / "stubs"), ("runtime", port_heaps_stubs.OUT / "runtime"),
                         ("lib/heaps-patched", port_heaps_stubs.HEAPS_PATCHED)):
        shutil.rmtree(engine / name, ignore_errors=True)
        shutil.copytree(source, engine / name)
    for name, target in HEAPS_LIBRARIES.items():
        source = port_heaps.library_path(name)
        shutil.rmtree(engine / target, ignore_errors=True)
        shutil.copytree(source, engine / target, ignore=shutil.ignore_patterns("*.hl", "*.dump"))
        for extra in ("LICENSE", "LICENSE.md", "LICENSE.txt", "haxelib.json"):
            for folder in (source, source.parent, source.parent.parent):
                if (folder / extra).exists() and not (engine / target / extra).exists():
                    shutil.copy2(folder / extra, engine / target / extra)
    haxe_dir = port_haxe_compile.HAXE.parent
    if not (engine / "tools" / "haxe" / "haxe.exe").exists():
        shutil.copytree(haxe_dir, engine / "tools" / "haxe", dirs_exist_ok=True)
    for folder, dxvk in (("bin", False), ("bin-vulkan", True)):
        run = port_heaps.prepare_run(dxvk)
        (engine / folder).mkdir(exist_ok=True)
        for source in run.iterdir():
            if source.suffix.lower() in (".exe", ".dll", ".hdll"):
                shutil.copy2(source, engine / folder / source.name)
    return 0


def write_heaps_hxml(engine: Path, game_src: str, what: str, defines: tuple[str, ...] = ()) -> None:
    from tools import port_heaps_stubs
    for renderer, driver in RENDERER_BUILDS:
        hxml = port_heaps_stubs.game_hxml(driver, f"bin/game-{renderer}.hl", "port.engine.HeapsMain", defines,
                                          cwd=".", game=game_src, stubs="src", runtime="runtime",
                                          patched="lib/heaps-patched", libraries=HEAPS_LIBRARIES)
        (engine / f"build-{renderer}.hxml").write_text(
            f"# {what} on the Heaps engine, {renderer} (generated by the port's export tools; see README.md)\n"
            + "\n".join(hxml) + "\n", encoding="utf-8")
    for old in (engine / "build-gl.hxml", engine / "bin" / "game-gl.hl"):
        old.unlink(missing_ok=True)
    (engine / "launcher.hxml").write_text(
        "# The renderer launcher (port.engine.Launcher; generated by the port's export tools)\n"
        "--cwd .\n--class-path src\n--main port.engine.Launcher\n--hl bin/launcher.hl\n", encoding="utf-8")


def migrate(engine: Path, openfl: Path) -> None:
    if (engine / ENGINE_MARKER).exists() and not (engine / HEAPS_MARKER).exists() and not openfl.exists():
        print(f"moving the OpenFL engine's earlier export {engine} -> {openfl} (the Heaps engine takes {engine.name})")
        engine.rename(openfl)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, required=True,
                        help="the raw game's folder (absolute path; outside any Git repo)")
    parser.add_argument("--engine", type=Path,
                        help=f"the Heaps engine's folder (default: {ENGINE_NAME} beside --out; outside any Git repo)")
    parser.add_argument("--openfl-engine", type=Path,
                        help=f"the OpenFL engine's folder (default: {OPENFL_ENGINE_NAME} beside --out)")
    parser.add_argument("--openfl-only", action="store_true",
                        help="only the raw game and the OpenFL engine (tools/port_heaps_stubs.py's refresh)")
    parser.add_argument("--convert", action="store_true", help="convert the AS3 tree again first")
    parser.add_argument("--game", type=Path, default=DEFAULT_GAME, help="run.bat's default install folder")
    parser.add_argument("--no-build", action="store_true", help="skip building with the engine's build.bat")
    parser.add_argument("--game-only", action="store_true",
                        help="only the raw game (the engine kit's Official build brings its own engine)")
    parser.add_argument("--version", default="10.11",
                        help="the game version (11.00 through tools/port_version_build.py run; folders under "
                             "build/ only)")
    args = parser.parse_args(argv)
    if args.version != port_haxe_compile.VERSION:
        port_haxe_compile.use_version(args.version)
    out = args.out.resolve()
    heaps = (args.engine or out.parent / ENGINE_NAME).resolve()
    openfl = (args.openfl_engine or out.parent / OPENFL_ENGINE_NAME).resolve()
    for folder in (out, heaps, openfl):
        if (ROOT / ".git").exists() and folder.is_relative_to(ROOT) and not folder.is_relative_to(ROOT / "build"):
            parser.error("export outside the repository (or under its ignored build/): the folders hold decompiled"
                         " code")
    if not args.openfl_only:
        migrate(heaps, openfl)
    rc = export(out, convert=args.convert, game=args.game, engine=openfl, game_only=args.game_only)
    if args.game_only:
        return rc
    if rc == 0 and not args.openfl_only:
        rc = export_heaps(out, heaps, openfl, args.game)
    if rc != 0 or args.no_build:
        return rc
    engine = openfl if args.openfl_only else heaps
    started = time.monotonic()
    result = subprocess.run(["cmd", "/c", str(engine / "build.bat")], cwd=engine, text=True, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT)
    print(result.stdout.strip()[-3000:])
    print(f"build.bat {'OK' if result.returncode == 0 else 'FAILED'} in {time.monotonic() - started:.0f} s")
    return result.returncode


if __name__ == "__main__":
    sys.exit(main())
